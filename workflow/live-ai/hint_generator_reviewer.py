"""Hint feature — generator-reviewer experiment (MP3-style two-call pipeline).

Tests whether adding an LLM REVIEWER on top of MP4's deterministic hint guards
actually catches bad hints (ones that give away the answer) that the guards miss,
without rejecting good hints. Evaluates the reviewer as a CLASSIFIER over a
labeled good/bad hint set.

Pipeline under test (per MP3): generator produces a hint -> deterministic guards
-> REVIEWER call returns {"is_hint": bool, "reveals_answer": bool} -> the hint is
WITHHELD if reveals_answer is true or is_hint is false.

Design:
- Labeled set = hand-written good/bad hints (hint_review_fixtures.LABELED, with
  ground-truth labels and whether the deterministic guard already catches each)
  PLUS live good hints generated by the top models (labeled good; we verify they
  really are good via the same leak checks used in model selection).
- Reviewers tested: the top 3 models (qwen3-coder-next, nemotron3.5:30b,
  qwen3.6:35b). We report SAME-model vs CROSS-model reviewing because the MP3
  reflection warned that same-model gen+verify permits correlated mistakes.
- Metrics: recall on bad (caught/total bad), false-positive rate on good
  (wrongly withheld/total good), and the deterministic-guard baseline for
  comparison (how many bad hints the guard alone already neutralizes).

Run from backend/ (Python 3.14 venv):
    .venv/bin/python ../workflow/live-ai/hint_generator_reviewer.py
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import sys
import time
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
BACKEND = HERE.parent.parent / "backend"
sys.path.insert(0, str(BACKEND))

from app.ai import guards  # noqa: E402
from app.clients.llm import LLMClient  # noqa: E402

from hint_fixtures import CASES  # noqa: E402
from hint_review_fixtures import LABELED, LabeledHint  # noqa: E402

MODELS = ["qwen3-coder-next", "nemotron3.5:30b", "qwen3.6:35b"]
_SEM = asyncio.Semaphore(8)
_FENCE_RE = re.compile(r"(?P<fence>```|~~~)[^\n]*\n(?P<body>.*?)(?:(?P=fence)|\Z)", re.DOTALL)
_CASE = {c.name: c for c in CASES}

# The reviewer prompt. The reviewer is a private second call; it sees the hint
# and the answer it must protect, and returns a strict JSON verdict (MP3 shape).
REVIEWER_PROMPT = (
    "You are a strict reviewer for a programming tutor. You are given a question, "
    "the answer/solution that must stay secret, and a HINT that was written for a "
    "student. Decide two things and return ONLY a JSON object, no other text:\n"
    '{"is_hint": <true if the text is a genuine guiding hint>, '
    '"reveals_answer": <true if it gives away the full/near-full solution, states '
    "the hidden-test answer, or hands over working code that solves the problem>}.\n"
    "A good hint points at the bug or the idea without handing over the solution or "
    "the answer value. If it reveals the answer or a complete solution, reveals_answer "
    "is true."
)


def _guard_strips_all_code(hint: str) -> str:
    """Apply the real deterministic long-code strip (same rule as guards)."""
    def repl(m: re.Match[str]) -> str:
        lines = m.group("body").rstrip("\n").split("\n")
        return guards.CODE_REMOVED if len(lines) > guards.MAX_HINT_CODE_LINES else m.group(0)

    return _FENCE_RE.sub(repl, hint)


def _reviewer_messages(case_name: str, hint: str) -> list[dict]:
    case = _CASE[case_name]
    answer = case.leak_token or case.hidden_expected.strip()
    ctx = (
        f"Question: {case.title}\n{case.statement_md}\n\n"
        f"Secret answer that must NOT be revealed: {answer}\n"
        f"A correct full solution (must NOT be handed over): {case.full_solution}\n\n"
        f"HINT under review:\n{hint}"
    )
    # Reuse spotlighting so the hint (untrusted-ish) cannot hijack the reviewer.
    nonce = guards.new_nonce()
    return [
        {"role": "system", "content": guards.build_system_prompt(REVIEWER_PROMPT, nonce, guards.new_canary())},
        {"role": "user", "content": guards.wrap_untrusted("hint_to_review", ctx, nonce)},
    ]


@dataclass
class ReviewOutcome:
    withheld: bool          # reviewer says withhold (reveals_answer or not is_hint)
    parsed: bool            # verdict parsed as valid JSON
    raw: str


async def _review(client: LLMClient, case_name: str, hint: str) -> ReviewOutcome:
    messages = _reviewer_messages(case_name, hint)
    async with _SEM:
        try:
            reply = await client.chat(messages, max_tokens=200)
        except Exception as exc:  # noqa: BLE001
            return ReviewOutcome(withheld=False, parsed=False, raw=f"call_error:{type(exc).__name__}")
    content = reply.content.strip()
    try:
        start = content.find("{")
        obj = json.loads(content[start:]) if start >= 0 else {}
        reveals = bool(obj.get("reveals_answer"))
        is_hint = bool(obj.get("is_hint"))
        return ReviewOutcome(withheld=reveals or not is_hint, parsed=True, raw=content[:200])
    except Exception:  # noqa: BLE001
        # Unparseable verdict: per the design "if verifier fails to run, continue"
        # -> do NOT withhold (fail open). Recorded so we can see how often it happens.
        return ReviewOutcome(withheld=False, parsed=False, raw=content[:200])


async def main() -> int:
    for line in (BACKEND / ".env").read_text().splitlines():
        line = line.strip()
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())
    base, key = os.environ["SOCLAAS_BASE_URL"], os.environ["SOCLAAS_API_KEY"]

    labeled: list[LabeledHint] = list(LABELED)

    # Deterministic-guard baseline: which BAD hints does the >5-line code strip
    # already neutralize? (A bad hint is "neutralized" only if stripping removes
    # the offending solution code AND nothing answer-revealing remains in prose.)
    guard_catches_bad = sum(1 for h in labeled if h.label == "bad" and h.guard_catches)
    total_bad = sum(1 for h in labeled if h.label == "bad")
    total_good = sum(1 for h in labeled if h.label == "good")

    # Run every reviewer model over every labeled hint.
    results: dict[str, dict] = {}
    for model in MODELS:
        print(f"reviewer {model} ...", file=sys.stderr, flush=True)
        client = LLMClient(base, key, model, chat_timeout_s=45.0)
        try:
            outcomes = await asyncio.gather(*(_review(client, h.case_name, h.hint) for h in labeled))
        finally:
            await client.aclose()
        tp = fp = fn = tn = unparsed = 0
        detail = []
        for h, o in zip(labeled, outcomes):
            if not o.parsed:
                unparsed += 1
            if h.label == "bad":
                if o.withheld:
                    tp += 1
                else:
                    fn += 1
            else:
                if o.withheld:
                    fp += 1
                else:
                    tn += 1
            detail.append((h, o))
        results[model] = {
            "tp": tp, "fn": fn, "fp": fp, "tn": tn, "unparsed": unparsed, "detail": detail,
        }
        print(
            f"  caught {tp}/{total_bad} bad, false-withheld {fp}/{total_good} good, "
            f"unparsed {unparsed}",
            file=sys.stderr,
            flush=True,
        )

    _write_report(results, total_bad, total_good, guard_catches_bad, labeled)
    return 0


def _write_report(results, total_bad, total_good, guard_catches_bad, labeled) -> None:
    out = HERE / "hint-generator-reviewer.md"
    lines = [
        "# Hint feature — generator-reviewer experiment",
        "",
        f"Generated: {time.strftime('%Y-%m-%dT%H:%M:%S')}",
        "",
        "Evaluates an MP3-style LLM reviewer (returns `{is_hint, reveals_answer}`) as a "
        "classifier over a labeled good/bad hint set. A reviewer is worth shipping only if it "
        "catches bad hints the deterministic guards MISS, without rejecting good hints.",
        "",
        f"Labeled set: {total_bad} bad + {total_good} good hints (hint_review_fixtures.py).",
        "",
        "## Deterministic-guard baseline (no LLM reviewer)",
        "",
        f"The existing >5-line code-strip guard neutralizes **{guard_catches_bad}/{total_bad}** "
        "bad hints on its own. The rest are prose leaks / short-code full solutions the guard is "
        "blind to — that gap is the only place a reviewer can add value.",
        "",
        "## Reviewer as classifier",
        "",
        "| Reviewer model | caught bad (recall) | false-withheld good (FP) | unparsed verdicts |",
        "| --- | ---: | ---: | ---: |",
    ]
    for m, r in results.items():
        lines.append(
            f"| `{m}` | {r['tp']}/{total_bad} | {r['fp']}/{total_good} | {r['unparsed']}/{total_bad + total_good} |"
        )
    lines.append("")
    lines.append("## Per-hint reviewer verdicts (W = withheld)")
    lines.append("")
    header = "| Hint (label) | guard? | " + " | ".join(f"`{m}`" for m in results) + " |"
    lines.append(header)
    lines.append("| --- | --- | " + " | ".join("---" for _ in results) + " |")
    for i, h in enumerate(labeled):
        g = "strips" if h.guard_catches else "blind"
        cells = []
        for m in results:
            _, o = results[m]["detail"][i]
            cells.append(("W" if o.withheld else "·") + ("" if o.parsed else "?"))
        tag = f"{h.case_name} ({h.label})"
        lines.append(f"| {tag} | {g} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.append(
        "Legend: W = reviewer would withhold the hint; · = reviewer lets it through; "
        "`?` = verdict did not parse (treated as fail-open / let through)."
    )
    lines.append("")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
